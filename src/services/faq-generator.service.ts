import { FAQItem } from '../types/blog.js';

export class FAQGeneratorService {
  generateFAQs(topic: string, count = 4): FAQItem[] {
    const faqs: FAQItem[] = [];

    if (topic.includes('लोक नृत्य') || topic.includes('नृत्य')) {
      faqs.push(
        {
          question: 'राजस्थान का राज्य नृत्य कौन-सा है और इसे किस नाम से जाना जाता है?',
          answer: 'राजस्थान का आधिकारिक राज्य नृत्य घूमर है। इसे "नृत्यों का सिरमौर" और "राजस्थान की आत्मा" भी कहा जाता है। यह मुख्यतः मांगलिक अवसरों और गणगौर पर्व पर महिलाओं द्वारा किया जाता है।',
        },
        {
          question: 'कालबेलिया नृत्य को यूनेस्को की धरोहर सूची में कब शामिल किया गया?',
          answer: 'कालबेलिया नृत्य को वर्ष 2010 में यूनेस्को की अमूर्त सांस्कृतिक विरासत (Intangible Cultural Heritage) सूची में शामिल किया गया था।',
        },
        {
          question: 'तेरहताली नृत्य में कितने मंजीरों का प्रयोग होता है और यह किस जाति द्वारा किया जाता है?',
          answer: 'तेरहताली नृत्य में कुल 13 मंजीरों का उपयोग किया जाता है (9 दाएं पैर पर, 2 कोहनियों पर और 2 हाथों में)। यह कामड़ जाति की महिलाओं द्वारा बाबा रामदेव जी की आराधना में किया जाता है।',
        },
        {
          question: 'RPSC और RSSB परीक्षाओं में राजस्थान के लोक नृत्यों से किस प्रकार के प्रश्न पूछे जाते हैं?',
          answer: 'परीक्षाओं में मुख्य रूप से नृत्यों का क्षेत्रीय वर्गीकरण (जैसे शेखावाटी का गीदड़, मेवात का बम), संबंधित जातियां (भील, गरासिया, कालबेलिया), प्रमुख वाद्य यंत्र एवं प्रसिद्ध कलाकारों से संबंधित प्रश्न पूछे जाते हैं।',
        }
      );
    } else if (topic.includes('CET')) {
      faqs.push(
        {
          question: 'राजस्थान CET परीक्षा क्या है और इसके क्या फायदे हैं?',
          answer: 'Rajasthan Common Eligibility Test (CET) एक समान पात्रता परीक्षा है, जिसे उत्तीर्ण करने वाले अभ्यर्थी राजस्थान सरकार की विभिन्न गैर-तकनीकी भर्तियों (जैसे पटवारी, ग्राम विकास अधिकारी, कनिष्ठ लेखाकार, एलडीसी आदि) की मुख्य परीक्षा के लिए पात्र होते हैं।',
        },
        {
          question: 'क्या CET परीक्षा में नेगेटिव मार्किंग होती है?',
          answer: 'आधिकारिक परीक्षा योजना के अनुसार समय-समय पर बोर्ड द्वारा जारी दिशा-निर्देश लागू होते हैं। नवीनतम नियमावली के अनुसार विस्तृत नोटिफिकेशन में अंकित प्रावधान मान्य होते हैं।',
        },
        {
          question: 'CET स्कोर कार्ड कितने समय के लिए वैध रहता है?',
          answer: 'सामान्यतः CET स्कोर कार्ड परीक्षा परिणाम जारी होने की तिथि से 1 वर्ष अथवा राज्य सरकार द्वारा समय-समय पर जारी संशोधित अधिसूचना के अनुसार मान्य रहता है।',
        },
        {
          question: 'CET की तैयारी के लिए राजस्थान जीके की तैयारी कैसे करें?',
          answer: 'राजस्थान जीके के लिए इतिहास, कला एवं संस्कृति, भूगोल और अर्थव्यवस्था के मानक नोट्स, विगत वर्षों के प्रश्न और दैनिक मॉक टेस्ट हल करने चाहिए।',
        }
      );
    } else {
      faqs.push(
        {
          question: `${topic} राजस्थान प्रतियोगी परीक्षाओं के लिए क्यों महत्वपूर्ण है?`,
          answer: `RPSC RAS, Rajasthan CET, REET, Police Constable एवं Sub-Inspector परीक्षाओं के आधिकारिक पाठ्यक्रम में ${topic} से प्रत्यक्ष प्रश्न पूछे जाते हैं।`,
        },
        {
          question: `${topic} के सबसे प्रमाणिक संदर्भ स्रोत कौन से हैं?`,
          answer: 'राजस्थान हिंदी ग्रंथ अकादमी की मानक पुस्तकें, माध्यमिक शिक्षा बोर्ड राजस्थान (RBSE) की पाठ्यपुस्तकें और राज्य सरकार के आधिकारिक गजेटियर सबसे विश्वसनीय स्रोत हैं।',
        },
        {
          question: 'इस विषय पर रिवीजन करने का सबसे प्रभावी तरीका क्या है?',
          answer: 'विषयवार तुलनात्मक सारणियों का अध्ययन करें, महत्वपूर्ण वन-लाइनर्स को दोहराएं और परीक्षा-पैटर्न आधारित बहुविकल्पीय प्रश्नों (MCQs) का नियमित अभ्यास करें।',
        }
      );
    }

    return faqs.slice(0, count);
  }
}
