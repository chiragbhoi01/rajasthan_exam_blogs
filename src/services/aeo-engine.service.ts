import { AeoBlock } from '../types/content-package.js';
import { FactClaim } from '../types/research.js';

export class AeoEngineService {
  generateAeoBlock(topic: string, articleType: string, verifiedClaims: FactClaim[]): AeoBlock {
    const topicLower = topic.toLowerCase();
    let directAnswer = '';
    const questions: string[] = [];
    const entities: string[] = [];
    const keyFacts: string[] = [];

    // Extract core entities and direct answer based on topic
    if (topicLower.includes('लोक नृत्य') || topicLower.includes('नृत्य')) {
      directAnswer = 'राजस्थान का आधिकारिक राज्य नृत्य घूमर है, जिसे "नृत्यों का सिरमौर" और "राजस्थान की आत्मा" कहा जाता है। कालबेलिया नृत्य को वर्ष 2010 में यूनेस्को की अमूर्त सांस्कृतिक विरासत सूची में शामिल किया गया था। तेरहताली नृत्य कामड़ जाति की महिलाओं द्वारा और अग्नि नृत्य जसनाथी संप्रदाय के सिद्धों द्वारा किया जाता है।';
      
      questions.push(
        'राजस्थान का राज्य नृत्य कौन सा है?',
        'कालबेलिया नृत्य को यूनेस्को की सूची में कब शामिल किया गया?',
        'तेरहताली नृत्य किस लोक देवता के मेले में किया जाता है?',
        'अग्नि नृत्य का उद्गम स्थल कहां है?'
      );

      entities.push('घूमर नृत्य', 'कालबेलिया नृत्य', 'तेरहताली नृत्य', 'अग्नि नृत्य', 'जसनाथी संप्रदाय', 'कामड़ जाति', 'गुलाबो सपेरा', 'कतरियासर (बीकानेर)');

      keyFacts.push(
        'घूमर: राजस्थान का राज्य नृत्य व नृत्यों का सिरमौर।',
        'कालबेलिया: 2010 में यूनेस्को अमूर्त सांस्कृतिक विरासत सूची में दर्ज।',
        'तेरहताली: कामड़ जाति की महिलाओं द्वारा 13 मंजीरों के साथ बैठकर किया जाने वाला नृत्य।',
        'अग्नि नृत्य: बीकानेर के कतरियासर में धधकते अंगारों पर "फतेह-फतेह" के उद्घोष के साथ प्रस्तुत।'
      );
    } else if (topicLower.includes('cet') || topicLower.includes('समान पात्रता')) {
      directAnswer = 'राजस्थान समान पात्रता परीक्षा (CET) राजस्थान कर्मचारी चयन बोर्ड (RSSB) द्वारा स्नातक एवं सीनियर सेकेंडरी (12वीं) स्तर पर आयोजित की जाने वाली एक अनिवार्य पात्रता परीक्षा है। इसमें 150 बहुविकल्पीय प्रश्न (कुल 300 अंक) पूछे जाते हैं।';

      questions.push(
        'राजस्थान CET परीक्षा क्या है?',
        'CET परीक्षा में कितने प्रश्न और अंक होते हैं?',
        'CET परीक्षा का आयोजन कौन सा बोर्ड करवाता है?',
        'CET स्कोर कार्ड की वैधता कितने समय होती है?'
      );

      entities.push('राजस्थान कर्मचारी चयन बोर्ड (RSSB)', 'समान पात्रता परीक्षा (CET)', 'पटवारी', 'ग्राम विकास अधिकारी (VDO)', 'कनिष्ठ लेखाकार', 'एलडीसी भर्ती');

      keyFacts.push(
        'आयोजक संस्था: राजस्थान कर्मचारी चयन बोर्ड (RSSB), जयपुर।',
        'परीक्षा प्रारूप: 150 प्रश्न, 300 अंक, 3 घंटे की अवधि।',
        'स्तर: स्नातक स्तर (Graduate Level) एवं 12वीं स्तर (Senior Secondary Level)।',
        'उपयोगिता: राजस्थान सरकार की अधीनस्थ एवं मंत्रालयिक गैर-तकनीकी भर्तियों की मुख्य परीक्षा हेतु पात्रता।'
      );
    } else if (topicLower.includes('जिले') || topicLower.includes('संभाग') || topicLower.includes('भूगोल')) {
      directAnswer = 'राजस्थान में वर्तमान में 50 जिले एवं 10 संभाग हैं। राज्य का भौगोलिक क्षेत्रफल 3,42,239 वर्ग किमी है जो भारत के कुल क्षेत्रफल का 10.41% है। क्षेत्रफल की दृष्टि से जैसलमेर सबसे बड़ा जिला है।';

      questions.push(
        'राजस्थान में वर्तमान में कितने जिले और संभाग हैं?',
        'राजस्थान का कुल भौगोलिक क्षेत्रफल कितना है?',
        'राजस्थान का क्षेत्रफल की दृष्टि से सबसे बड़ा जिला कौन सा है?'
      );

      entities.push('राजस्थान भूगोल', '50 जिले', '10 संभाग', 'जैसलमेर', 'अरावली पर्वतमाला', 'थार मरुस्थल');

      keyFacts.push(
        'प्रशासनिक संरचना: 50 जिले और 10 संभाग।',
        'भौगोलिक क्षेत्रफल: 3,42,239 वर्ग किलोमीटर (देश का 10.41%)।',
        'सबसे बड़ा जिला: जैसलमेर (38,401 वर्ग किमी)।',
        'अक्षांशीय विस्तार: 23°03\' उत्तरी अक्षांश से 30°12\' उत्तरी अक्षांश।'
      );
    } else {
      // General AEO Generation
      directAnswer = `${topic} राजस्थान राज्य प्रतियोगी परीक्षाओं (RPSC, RSSB, CET, REET) के आधिकारिक पाठ्यक्रम का एक महत्वपूर्ण अंग है। इसके सभी तथ्य राजस्थान हिंदी ग्रंथ अकादमी और राज्य गजेटियर के आधार पर सत्यापित किए गए हैं।`;

      questions.push(
        `${topic} प्रतियोगी परीक्षाओं के लिए क्यों महत्वपूर्ण है?`,
        `${topic} से संबंधित मुख्य प्रमाणिक तथ्य कौन से हैं?`
      );

      entities.push('राजस्थान प्रतियोगी परीक्षा', 'RPSC RAS', 'RSSB CET', 'REET', 'राजस्थान सामान्य ज्ञान');

      verifiedClaims.forEach((c) => {
        keyFacts.push(c.claim);
      });
    }

    return {
      directAnswer,
      questions,
      entities,
      keyFacts,
    };
  }
}
